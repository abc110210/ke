static const uint8_t RCON[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36};

// GF(2^8) 乘法（约简多项式 0x11b）
static inline uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        uint8_t hi = a & 0x80;
        a <<= 1;
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

// 密钥扩展：32 字节密钥 -> 240 字节轮密钥（标准字节序，与 BCrypt 一致）
static inline void key_expand(const uint8_t key[32], uint8_t rk[240]) {
    for (int i = 0; i < 32; i++) rk[i] = key[i];
    int bytes = 32;
    uint8_t temp[4];
    while (bytes < 240) {
        for (int i = 0; i < 4; i++) temp[i] = rk[bytes - 4 + i];
        if (bytes % 32 == 0) {
            // RotWord
            uint8_t t = temp[0]; temp[0] = temp[1]; temp[1] = temp[2]; temp[2] = temp[3]; temp[3] = t;
            // SubWord
            for (int i = 0; i < 4; i++) temp[i] = SBOX[temp[i]];
            // Rcon
            temp[0] ^= RCON[bytes / 32];
        } else if (bytes % 32 == 16) {
            // AES-256：每第 4 个字额外做一次 SubWord
            for (int i = 0; i < 4; i++) temp[i] = SBOX[temp[i]];
        }
        for (int i = 0; i < 4; i++) {
            rk[bytes] = static_cast<uint8_t>(rk[bytes - 32] ^ temp[i]);
            bytes++;
        }
    }
}

static inline void sub_bytes(uint8_t s[16])   { for (int i=0;i<16;i++) s[i]=SBOX[s[i]]; }
static inline void inv_sub_bytes(uint8_t s[16]){ for (int i=0;i<16;i++) s[i]=SBOX_INV[s[i]]; }

static inline void shift_rows(uint8_t s[16]) {
    uint8_t t[16];
    for (int r=0;r<4;r++) for (int c=0;c<4;c++) t[r+4*c] = s[r+4*((c+r)&3)];
    memcpy(s, t, 16);
}
static inline void inv_shift_rows(uint8_t s[16]) {
    uint8_t t[16];
    for (int r=0;r<4;r++) for (int c=0;c<4;c++) t[r+4*c] = s[r+4*((c-r)&3)];
    memcpy(s, t, 16);
}

static inline void mix_columns(uint8_t s[16]) {
    for (int c=0;c<4;c++) {
        uint8_t a0=s[0+4*c],a1=s[1+4*c],a2=s[2+4*c],a3=s[3+4*c];
        s[0+4*c] = static_cast<uint8_t>(gmul(a0,2)^gmul(a1,3)^a2^a3);
        s[1+4*c] = static_cast<uint8_t>(a0^gmul(a1,2)^gmul(a2,3)^a3);
        s[2+4*c] = static_cast<uint8_t>(a0^a1^gmul(a2,2)^gmul(a3,3));
        s[3+4*c] = static_cast<uint8_t>(gmul(a0,3)^a1^a2^gmul(a3,2));
    }
}
static inline void inv_mix_columns(uint8_t s[16]) {
    for (int c=0;c<4;c++) {
        uint8_t a0=s[0+4*c],a1=s[1+4*c],a2=s[2+4*c],a3=s[3+4*c];
        s[0+4*c] = static_cast<uint8_t>(gmul(a0,14)^gmul(a1,11)^gmul(a2,13)^gmul(a3,9));
        s[1+4*c] = static_cast<uint8_t>(gmul(a0,9)^gmul(a1,14)^gmul(a2,11)^gmul(a3,13));
        s[2+4*c] = static_cast<uint8_t>(gmul(a0,13)^gmul(a1,9)^gmul(a2,14)^gmul(a3,11));
        s[3+4*c] = static_cast<uint8_t>(gmul(a0,11)^gmul(a1,13)^gmul(a2,9)^gmul(a3,14));
    }
}

static inline void add_round_key(uint8_t s[16], const uint8_t rk[240], int round) {
    for (int i=0;i<16;i++) s[i] ^= rk[round*16 + i];
}

static inline void encrypt_block(const uint8_t in[16], uint8_t out[16], const uint8_t rk[240]) {
    uint8_t s[16]; memcpy(s, in, 16);
    add_round_key(s, rk, 0);
    for (int r=1;r<=13;r++) {
        sub_bytes(s); shift_rows(s); mix_columns(s); add_round_key(s, rk, r);
    }
    sub_bytes(s); shift_rows(s); add_round_key(s, rk, 14);
    memcpy(out, s, 16);
}

static inline void decrypt_block(const uint8_t in[16], uint8_t out[16], const uint8_t rk[240]) {
    uint8_t s[16]; memcpy(s, in, 16);
    add_round_key(s, rk, 14);
    for (int r=13;r>=1;r--) {
        inv_shift_rows(s); inv_sub_bytes(s); add_round_key(s, rk, r); inv_mix_columns(s);
    }
    inv_shift_rows(s); inv_sub_bytes(s); add_round_key(s, rk, 0);
    memcpy(out, s, 16);
}

// CBC（无填充，调用方保证 len 为 16 的倍数；原地加解密安全：先读入临时块再写回）
static inline void cbc_encrypt(const uint8_t key[32], const uint8_t iv[16],
                               const uint8_t* in, size_t len, uint8_t* out) {
    uint8_t rk[240]; key_expand(key, rk);
    uint8_t ivc[16]; memcpy(ivc, iv, 16);
    for (size_t off=0; off<len; off+=16) {
        uint8_t blk[16];
        for (int i=0;i<16;i++) blk[i] = static_cast<uint8_t>(in[off+i] ^ ivc[i]);
        uint8_t enc[16];
        encrypt_block(blk, enc, rk);
        memcpy(out+off, enc, 16);
        memcpy(ivc, enc, 16);
    }
}

static inline void cbc_decrypt(const uint8_t key[32], const uint8_t iv[16],
                               const uint8_t* in, size_t len, uint8_t* out) {
    uint8_t rk[240]; key_expand(key, rk);
    uint8_t ivc[16]; memcpy(ivc, iv, 16);
    for (size_t off=0; off<len; off+=16) {
        uint8_t dec[16];
        decrypt_block(in+off, dec, rk);
        for (int i=0;i<16;i++) out[off+i] = static_cast<uint8_t>(dec[i] ^ ivc[i]);
        memcpy(ivc, in+off, 16);
    }
}

